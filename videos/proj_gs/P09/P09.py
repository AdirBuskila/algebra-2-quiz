def qr(A):
    cols = [A[:, j] for j in range(A.cols)]
    us, cs = w.gram_schmidt(cols, w.dot)
    qs = [u / sp.sqrt(w.dot(u, u)) for u in us]
    Q = sp.Matrix.hstack(*qs)
    Rm = sp.simplify(Q.T * A)
    assert sp.simplify(Q.T * Q) == sp.eye(A.cols)
    assert all(Rm[i, j] == 0 for i in range(Rm.rows) for j in range(i))           # upper triangular
    assert sp.simplify(Q * Rm - A) == sp.zeros(A.rows, A.cols)
    for i in range(A.cols):
        assert sp.simplify(Rm[i, i] - sp.sqrt(w.dot(us[i], us[i]))) == 0           # r_ii = |u_i|
        for j in range(i + 1, A.cols):
            assert sp.simplify(Rm[i, j] - w.dot(cols[j], qs[i])) == 0             # r_ij = <a_j, q_i>
    return us, cs, qs, Q, Rm


# ---------------------------------------------------------------- example: A = [[3,-1],[4,7]]
A = M([[4, 1], [3, 7]])
us, cs, qs, Q, Rm = qr(A)
assert list(us[0]) == [4, 3] and w.dot(us[0], us[0]) == 25
assert list(qs[0]) == [R(4, 5), R(3, 5)] and w.dot(A[:, 1], qs[0]) == 5
assert list(us[1]) == [-3, 4] and list(qs[1]) == [R(-3, 5), R(4, 5)]
assert Q == M([[R(4, 5), R(-3, 5)], [R(3, 5), R(4, 5)]]) and Rm == M([[5, 5], [0, 5]])
# the trap: <a_2, u_1> instead of <a_2, q_1>
assert w.dot(A[:, 1], us[0]) == 25 and w.dot(A[:, 1], us[0]) != Rm[0, 1]
# solving Ax = b with QR
b = V(6, 17)
Qtb = Q.T * b
assert list(Qtb) == [15, 10]
xs = Rm.LUsolve(Qtb)
assert list(xs) == [1, 2] and A * xs == b

