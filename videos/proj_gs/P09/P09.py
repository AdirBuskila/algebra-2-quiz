assert sp.simplify(Q3 - M([[1, 1, 0], [0, 0, s2], [1, -1, 0]]) / s2) == sp.zeros(3, 3)     # the form on screen
assert sp.simplify(R3 - M([[2, 0, 1], [0, 2, -1], [0, 0, s2]]) / s2) == sp.zeros(3, 3)

