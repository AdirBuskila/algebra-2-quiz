# ---------------------------------------------------------------- verified facts
assert [(7 * k) % 9 for k in (1, 2, 3, 4)] == [7, 5, 3, 1] and w.inv_mod(7, 9) == 4
assert sorted({(4 * k) % 6 for k in range(6)}) == [0, 2, 4]          # 4x mod 6 is never 1: no inverse
divs, x11 = w.euclid(11, 26)
assert divs == [(26, 2, 11, 4), (11, 2, 4, 3), (4, 1, 3, 1)] and x11 == 19
assert 3 * 26 - 7 * 11 == 1 and (-7) % 26 == 19 and 11 * 19 == 209 == 8 * 26 + 1
assert w.inv_mod(4, 11) == 3 and w.solve_linear(4, 5, 11) == [4] and 4 * 4 == 16 == 11 + 5
assert (-3) % 8 == 5 and 40 % 9 == 4
assert w.solve_linear(4, 3, 6) == []

# exam 24B-A-Q2a/b: G = {(a, a^2) : a in Z_7^*} with componentwise multiplication mod 7
assert "(1,1)" in BANK["24B-A-Q2a"]["solution"] and "(4,2)" in BANK["24B-A-Q2b"]["solution"]
G = [(a, (a * a) % 7) for a in w.zstar(7)]
mul = lambda p, q: ((p[0] * q[0]) % 7, (p[1] * q[1]) % 7)
RG = w.group_report(G, mul)
assert RG["group"] and RG["neutral"] == (1, 1)
assert (2, 4) in G and RG["inverses"][(2, 4)] == [(4, 2)]
assert w.inv_mod(2, 7) == 4 and w.inv_mod(4, 7) == 2 and (4 * 4) % 7 == 2
assert mul((2, 4), (5, 3)) == (3, 5) != (1, 1)                      # (-2,-4) = (5,3) is not the inverse

TRY = w.lines("t", ["$7\\cdot1=7$", "$7\\cdot2=14\\equiv5$", "$7\\cdot3=21\\equiv3$",
                    "$7\\cdot4=28\\equiv1\\ \\ \\checkmark$"], size=40)
EUC = w.lines("u", [f"${b}={q}\\cdot{s}+{r}$" for b, q, s, r in divs]
              + ["$1=4-3=4-(11-2\\cdot4)=3\\cdot4-11$", "$1=3(26-2\\cdot11)-11=3\\cdot26-7\\cdot11$",
                 "$11^{-1}\\equiv-7\\equiv19\\pmod{26}$"], size=34)

