# 25A-A-Q4a/b
assert "o(J)=4" in BANK["25A-A-Q4a"]["solution"].replace(" ", "")
J = ((0, 4), (1, 0))
det = (0 * 0 - 4 * 1) % 5
assert det == 1
Jp = [w.mpow(J, k, 5) for k in range(1, 5)]
assert Jp == [((0, 4), (1, 0)), ((4, 0), (0, 4)), ((0, 1), (4, 0)), ((1, 0), (0, 1))] and w.morder(J, 5) == 4
GL = [M for M in (((a, b), (c, d)) for a, b, c, d in product(range(5), repeat=4)) if (M[0][0] * M[1][1] - M[0][1] * M[1][0]) % 5]
assert len(GL) == 480 and 480 % 4 == 0

# 26A-A-Q4b
assert "(2,-1)" in BANK["26A-A-Q4b"]["solution"].replace(" ", "")
circ = lambda p, q: (p[0] + q[0], p[1] + (-1) ** (p[0] % 2) * q[1])
win = list(product(range(-3, 4), repeat=2))
assert all(circ(circ(p, q), r) == circ(p, circ(q, r)) for p in win for q in win for r in win)   # associative (window)
assert all(circ((0, 0), p) == p == circ(p, (0, 0)) for p in win)                                  # neutral (0,0)
assert all(circ(p, (-p[0], -((-1) ** (p[0] % 2)) * p[1])) == (0, 0) for p in win)                 # inverses
assert circ((1, 1), (1, 0)) == (2, 1) and circ((1, 0), (1, 1)) == (2, -1)
assert circ((2, 1), (2, 3)) == circ((2, 3), (2, 1))                                                # even a: they commute

