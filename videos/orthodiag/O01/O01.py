# ---------------------------------------------------------------- verified facts
M1 = S([[4, -2, 7], [-2, 1, 0], [7, 0, 5]])            # symmetric
M2 = S([[4, -2, 7], [3, 1, 0], [7, 0, 5]])             # not: a12 = -2, a21 = 3
assert M1 == M1.T and M2 != M2.T and M2[0, 1] != M2[1, 0]

N = S([[1, 2], [0, 3]])                                  # diagonalizable, not symmetric
assert N.is_diagonalizable() and N != N.T
assert sorted(N.eigenvals(multiple=True)) == [1, 3]
w.eig_pairs(N, [(1, [1, 0]), (3, [1, 1])])
assert N.eigenvects()[0][2][0].dot(N.eigenvects()[1][2][0]) != 0   # the only eigen-directions are not perpendicular

E1 = S([[5, 2], [2, 2]])
assert E1.trace() == 7 and E1.det() == 6 and sorted(E1.eigenvals(multiple=True)) == [1, 6]
assert sp.expand(E1.charpoly(lam).as_expr()) == lam**2 - 7 * lam + 6
E2 = S([[2, 1], [1, 1]])
assert E2.trace() == 3 and E2.det() == 1
assert set(E2.eigenvals()) == {(3 + sp.sqrt(5)) / 2, (3 - sp.sqrt(5)) / 2}

# exam-style question (original, bank={}): for which t is M(t) orthogonally diagonalizable, and its eigenvalues
t = sp.symbols("t", real=True)
X = S([[2, t + 1, 0], [t**2 - 1, 2, 0], [0, 0, t]])
assert all(X[i, j] == X[j, i] for i in range(3) for j in range(3) if {i, j} != {0, 1})
assert set(sp.solve(sp.Eq(X[0, 1], X[1, 0]), t)) == {-1, 2}
assert sp.factor(t**2 - 1 - (t + 1)) == (t - 2) * (t + 1)
X2, Xm = X.subs(t, 2), X.subs(t, -1)
assert X2 == X2.T and Xm == Xm.T
assert X2 * S([0, 0, 1]) == 2 * S([0, 0, 1])
B = X2[:2, :2]
assert B == S([[2, 3], [3, 2]]) and B.trace() == 4 and B.det() == -5 and sorted(B.eigenvals(multiple=True)) == [-1, 5]
assert sorted(X2.eigenvals(multiple=True)) == [-1, 2, 5]
assert Xm == sp.diag(2, 2, -1)
w.orth_diag(X2, [(5, [1, 1, 0]), (-1, [1, -1, 0]), (2, [0, 0, 1])])
# the trap: t = 3 is diagonalizable (three distinct real eigenvalues) but not symmetric
X3 = X.subs(t, 3)
assert X3 != X3.T and X3.is_diagonalizable()
assert set(X3.eigenvals()) == {3, 2 + 4 * sp.sqrt(2), 2 - 4 * sp.sqrt(2)}
