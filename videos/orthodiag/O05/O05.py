x1, x2 = sp.symbols("x1 x2")
xv = S([x1, x2])


def form(M):
    return sp.expand((xv.T * M * xv)[0])


# ---------------------------------------------------------------- computing a form
A = S([[2, 4], [4, 1]])
assert form(A) == 2 * x1**2 + 8 * x1 * x2 + x2**2
v = S([1, 1])
assert A * v == S([6, 5]) and v.dot(A * v) == 11 and form(A).subs({x1: 1, x2: 1}) == 11

# ---------------------------------------------------------------- a negative vector
B = S([[6, 6], [6, 1]])
assert form(B) == 6 * x1**2 + 12 * x1 * x2 + x2**2
assert B.trace() == 7 and B.det() == -30 and sorted(B.eigenvals(multiple=True)) == [-3, 10]
e = S([2, -3])
w.eig_pairs(B, [(-3, e)])
assert e.dot(B * e) == -39 == -3 * e.dot(e)
assert form(B).subs({x1: 2, x2: -3}) == 24 - 72 + 9 == -39
assert sp.expand(6 * (x1 + x2)**2 - 5 * x2**2) == form(B)
assert form(B).subs({x1: 1, x2: -1}) == -5
assert form(B).subs({x1: 1, x2: 0}) == 6 and form(B).subs({x1: 0, x2: 1}) == 1       # the diagonal alone looks positive
# unit eigenvector: v^T A v = lambda
u = e / w.norm(e)
assert sp.simplify(u.dot(B * u)) == -3

# ---------------------------------------------------------------- exam 23B-A-Q2c: the identities, for a general symmetric 3x3
X = BANK["23B-A-Q2c"]
assert "I+A" in X["question"] and "A^2" in X["question"]
a = sp.symbols("a0:6")
G = S([[a[0], a[1], a[2]], [a[1], a[3], a[4]], [a[2], a[4], a[5]]])
y = S(sp.symbols("y0:3"))
assert G == G.T
assert sp.expand((y.T * (sp.eye(3) + G) * y)[0] - (y.dot(y) + (y.T * G * y)[0])) == 0
assert sp.expand((y.T * G**2 * y)[0] - (G * y).dot(G * y)) == 0
assert (sp.eye(3) + G).T == sp.eye(3) + G and (G**2).T == G**2
# and why symmetry is needed: for a non-symmetric N, y^T N^2 y is not |Ny|^2
N = S([[0, 1], [0, 0]])
z = S([1, 1])
assert (z.T * N**2 * z)[0] == 0 and (N * z).dot(N * z) == 1

