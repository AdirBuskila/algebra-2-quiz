# ---------------------------------------------------------------- example 1: different eigenvalues
A1 = S([[3, 2], [2, 0]])
w.eig_pairs(A1, [(4, [2, 1]), (-1, [1, -2])])
assert sorted(A1.eigenvals(multiple=True)) == [-1, 4]
assert S([2, 1]).dot(S([1, -2])) == 0

# ---------------------------------------------------------------- example 2: a double eigenvalue, Gram-Schmidt
u = S([1, 2, 2])
A2 = sp.eye(3) + u * u.T
assert A2 == S([[2, 2, 2], [2, 5, 4], [2, 4, 5]])
assert sorted(A2.eigenvals(multiple=True)) == [1, 1, 10]
w1, w2 = S([2, -1, 0]), S([2, 0, -1])
w.eig_pairs(A2, [(1, w1), (1, w2), (10, u)])
assert w1.dot(w2) == 4 and w1.dot(w1) == 5
c = R(w2.dot(w1), w1.dot(w1))
assert c == R(4, 5)
w2p = w2 - c * w1
assert w2p == S([R(2, 5), R(4, 5), -1]) and 5 * w2p == S([2, 4, -5])
w.eig_pairs(A2, [(1, 5 * w2p)])
assert (5 * w2p).dot(w1) == 0 and (5 * w2p).dot(u) == 0 and w1.dot(u) == 0
assert w.norm(5 * w2p) == 3 * sp.sqrt(5) and w.norm(w1) == sp.sqrt(5) and w.norm(u) == 3
Q2, D2 = w.orth_diag(A2, [(1, [2, -1, 0]), (1, [2, 4, -5]), (10, [1, 2, 2])])

# ---------------------------------------------------------------- exam 24B-A-Q5a
Q = BANK["24B-A-Q5a"]
A = S([[1, 1, 0], [1, 1, 0], [0, 0, 2]])
assert "\\begin{pmatrix}1&1&0\\\\1&1&0\\\\0&0&2\\end{pmatrix}" in Q["question"]
assert A * S([0, 0, 1]) == 2 * S([0, 0, 1])                       # third row/column isolated
B = A[:2, :2]
assert B.trace() == 2 and B.det() == 0 and sorted(B.eigenvals(multiple=True)) == [0, 2]
assert sorted(A.eigenvals(multiple=True)) == [0, 2, 2]
assert (A - 2 * sp.eye(3)).rank() == 1                              # eigenspace of 2 has dimension 2
assert (A - 2 * sp.eye(3)).nullspace() and len((A - 2 * sp.eye(3)).nullspace()) == 2
v1, v2, v3 = S([1, 1, 0]), S([0, 0, 1]), S([1, -1, 0])
w.eig_pairs(A, [(2, v1), (2, v2), (0, v3)])
assert v1.dot(v2) == 0 and v1.dot(v3) == 0 and v2.dot(v3) == 0
alt = S([1, 1, 1])                                                  # also in the eigenspace of 2, not perpendicular
w.eig_pairs(A, [(2, alt)])
assert alt.dot(v2) == 1
QA, DA = w.orth_diag(A, [(2, [1, 1, 0]), (2, [0, 0, 1]), (0, [1, -1, 0])])
assert DA == sp.diag(2, 2, 0)

