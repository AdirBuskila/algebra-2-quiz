"""V06 · השלמת U ו-V: מטריצה לא ריבועית או חסרת דרגה — video script (build: tools/video/vid.py V06).

Source: courses/svd/C06.js (lesson + goal: complete the missing columns of U and V to an orthonormal basis; in U by a
cross product in R^3 or by orthogonality + Gram-Schmidt, in V from ker A).
Exam anchor: none (the three free svd exam parts are solved in V02 and V08). Original question "בסגנון מבחן"
(bank={}): the full SVD of the rank-1 all-ones 3x2 matrix: sigma = sqrt6, 0; v_2 from ker A; u_1 by the formula; u_2,
u_3 an orthonormal basis of the plane x+y+z = 0 (a cross product for the last one).
Avoided on purpose: the C06 quiz (4x2 count, (1,1,0)x(-1,1,0), [[1,0,2],[2,0,1]], [[1,2],[2,4]]) and every quiz/boss
matrix. Worked examples: the lesson's u_3 for [[1,1],[0,1],[1,0]] and V for the original 2x3 [[2,1,1],[1,2,-1]].
Everything is asserted with sympy (w_svd.check_svd on each full decomposition).
"""
import sympy as sp
from vid import P, Scene, Video, show, hide
import stage as st
import w_svd as w

M = sp.Matrix
s3, s6 = sp.sqrt(3), sp.sqrt(6)

# example U: the course matrix
A1 = M([[1, 1], [0, 1], [1, 0]])
c = M([2, 1, 1]).cross(M([0, -1, 1]))
assert c == M([2, -2, -2]) and c.norm() == 2 * s3
assert M([1, -1, -1]).dot(M([2, 1, 1])) == 0 and M([1, -1, -1]).dot(M([0, -1, 1])) == 0
_, U1 = w.cols((2, 1, 1), (0, -1, 1), (1, -1, -1))
_, V1 = w.cols((1, 1), (1, -1))
assert w.check_svd(A1, U1, w.S_mat(3, 2, [s3, 1]), V1)

# example V: the 2x3 [[2,1,1],[1,2,-1]] through AA^T
A2 = M([[2, 1, 1], [1, 2, -1]])
assert A2 * A2.T == M([[6, 3], [3, 6]]) and w.eig_desc(A2 * A2.T) == [9, 3]
u1, u2 = w.unit((1, 1)), w.unit((1, -1))
assert w.is_eigvec(A2 * A2.T, 9, u1) and w.is_eigvec(A2 * A2.T, 3, u2)
assert sp.simplify(A2.T * u1 / 3 - w.unit((1, 1, 0))) == sp.zeros(3, 1)
assert sp.simplify(A2.T * u2 / s3 - w.unit((1, -1, 2))) == sp.zeros(3, 1)
k = M([1, -1, -1])
assert A2 * k == sp.zeros(2, 1) and A2.nullspace()[0].cross(k) == sp.zeros(3, 1)
assert M([1, 1, 0]).cross(M([1, -1, 2])) == 2 * k                  # in R^3 a cross product gives the same line
_, U2 = w.cols((1, 1), (1, -1))
V2tex, V2 = w.cols((1, 1, 0), (1, -1, 2), (1, -1, -1))
assert w.check_svd(A2, U2, w.S_mat(2, 3, [3, s3]), V2)

# exam-style: all ones 3x2, rank 1
X = M([[1, 1], [1, 1], [1, 1]])
assert X.T * X == M([[3, 3], [3, 3]]) and w.eig_desc(X.T * X) == [6, 0]
xv1, xv2 = w.unit((1, 1)), w.unit((1, -1))
assert X * M([1, -1]) == sp.zeros(3, 1)
assert sp.simplify(X * xv1 - M([2, 2, 2]) / sp.sqrt(2)) == sp.zeros(3, 1)
xu1 = X * xv1 / s6
assert sp.simplify(xu1 - w.unit((1, 1, 1))) == sp.zeros(3, 1)
p = M([1, -1, 0])
assert p.dot(M([1, 1, 1])) == 0
q = M([1, 1, 1]).cross(p)
assert q == M([1, 1, -2]) and q.dot(p) == 0 and q.dot(M([1, 1, 1])) == 0
UXtex, UX = w.cols((1, 1, 1), (1, -1, 0), (1, 1, -2))
VXtex, VX = w.cols((1, 1), (1, -1))
VXt_tex, _ = w.cols_T((1, 1), (1, -1))
SX = w.S_mat(3, 2, [s6, 0])
assert w.check_svd(X, UX, SX, VX)

