import w_svd as w

M = sp.Matrix
L = sp.Symbol("lambda")
s2, s3 = sp.sqrt(2), sp.sqrt(3)

# ---------------------------------------------------------------- 23A-A-Q5a
Q1 = "23A-A-Q5a"
A = M([[-1, 1], [-1, 1], [1, 1]])
B = A.T * A
assert B == M([[3, -1], [-1, 3]])
assert sp.expand((B - L * sp.eye(2)).det() - ((3 - L) ** 2 - 1)) == 0
assert w.eig_desc(B) == [4, 2]
sA = [2, s2]
assert [w.sig(l) for l in [4, 2]] == sA
assert (B - 4 * sp.eye(2)) * M([1, -1]) == sp.zeros(2, 1) and (B - 2 * sp.eye(2)) * M([1, 1]) == sp.zeros(2, 1)
av1, av2 = w.unit((1, -1)), w.unit((1, 1))
assert A * M([1, -1]) == M([-2, -2, 0]) and A * M([1, 1]) == M([0, 0, 2])
au1, au2 = A * av1 / 2, A * av2 / s2
assert sp.simplify(au1 - w.unit((-1, -1, 0))) == sp.zeros(3, 1) and au2 == M([0, 0, 1])
au3 = M([1, -1, 0])
assert au3.dot(M([-1, -1, 0])) == 0 and au3.dot(M([0, 0, 1])) == 0 and A.T * au3 == sp.zeros(2, 1)
AU_tex, AU = w.cols((-1, -1, 0), (0, 0, 1), (1, -1, 0))
AVt_tex, _ = w.cols_T((1, -1), (1, 1))
_, AV = w.cols((1, -1), (1, 1))
AS = w.S_mat(3, 2, sA)
assert w.check_svd(A, AU, AS, AV)
assert sum(x ** 2 for x in A) == 6 == 4 + 2

# ---------------------------------------------------------------- 24A-C-Q3a
Q2 = "24A-C-Q3a"
X = M([[0, -1, 1], [1, 1, 0]])
C = X * X.T
assert C == M([[2, -1], [-1, 2]])
assert sp.expand((C - L * sp.eye(2)).det() - ((2 - L) ** 2 - 1)) == 0
assert w.eig_desc(C) == [3, 1] and w.eig_desc(X.T * X) == [3, 1, 0]
sX = [s3, 1]
xu1, xu2 = w.unit((-1, 1)), w.unit((1, 1))
assert w.is_eigvec(C, 3, xu1) and w.is_eigvec(C, 1, xu2)
assert X.T * M([-1, 1]) == M([1, 2, -1]) and X.T * M([1, 1]) == M([1, 0, 1])
xv1, xv2 = X.T * xu1 / s3, X.T * xu2 / 1
assert sp.simplify(xv1 - w.unit((1, 2, -1))) == sp.zeros(3, 1) and sp.simplify(xv2 - w.unit((1, 0, 1))) == sp.zeros(3, 1)
k = M([-1, 1, 1])
assert X * k == sp.zeros(2, 1) and k.dot(M([1, 2, -1])) == 0 and k.dot(M([1, 0, 1])) == 0
XU_tex, XU = w.cols((-1, 1), (1, 1))
XVt_tex, _ = w.cols_T((1, 2, -1), (1, 0, 1), (-1, 1, 1))
_, XV = w.cols((1, 2, -1), (1, 0, 1), (-1, 1, 1))
XS = w.S_mat(2, 3, sX)
assert w.check_svd(X, XU, XS, XV)
assert sum(x ** 2 for x in X) == 4 == 3 + 1


