M = sp.Matrix

# example (lesson): A^T A = [[2,1],[1,2]]
B = M([[2, 1], [1, 2]])
assert w.eig_desc(B) == [3, 1]
assert (B - 3 * sp.eye(2)) * M([1, 1]) == sp.zeros(2, 1) and (B - sp.eye(2)) * M([1, -1]) == sp.zeros(2, 1)
Vtex, V = w.cols((1, 1), (1, -1))
assert w.is_orth(V)

# exam-style: A = [I; w^T]
wv = M([1, 1, 2])
A = M.vstack(sp.eye(3), wv.T)
G = A.T * A
assert G == M([[2, 1, 2], [1, 2, 2], [2, 2, 5]]) and G == sp.eye(3) + wv * wv.T
assert (G - sp.eye(3)).rank() == 1 and G.trace() == 9
assert w.eig_desc(G) == [7, 1, 1]
assert G * wv == 7 * wv
p1, p2 = M([-1, 1, 0]), M([-2, 0, 1])
assert (G - sp.eye(3)) * p1 == sp.zeros(3, 1) and (G - sp.eye(3)) * p2 == sp.zeros(3, 1)
assert p1.dot(p2) == 2                                  # the obvious pair is not orthogonal
q2 = p2 - (p2.dot(p1) / p1.dot(p1)) * p1
assert q2 == M([-1, -1, 1]) and q2.dot(p1) == 0 and (G - sp.eye(3)) * q2 == sp.zeros(3, 1)
VXtex, VX = w.cols((1, 1, 2), (-1, 1, 0), (-1, -1, 1))
assert w.is_orth(VX)
for i, lam in enumerate([7, 1, 1]):
    assert w.is_eigvec(G, lam, VX[:, i])
assert [w.sig(l) for l in [7, 1, 1]] == [sp.sqrt(7), 1, 1]

