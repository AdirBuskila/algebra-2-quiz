M = sp.Matrix
s3, s6 = sp.sqrt(3), sp.sqrt(6)

# ---------------------------------------------------------------- worked example (original)
A = M([[2, 1, 0], [0, 1, 2]])
AAT, ATA = A * A.T, A.T * A
assert AAT == M([[5, 1], [1, 5]]) and ATA == M([[4, 2, 0], [2, 2, 2], [0, 2, 4]])
assert w.eig_desc(AAT) == [6, 4] and w.eig_desc(ATA) == [6, 4, 0]
assert AAT.trace() == ATA.trace() == sum(x ** 2 for x in A) == 10

# ---------------------------------------------------------------- exam 25A-A-Q5a
X = M([[1, 1, 1], [1, -2, 1]])
XXT = X * X.T
assert XXT == M([[3, 0], [0, 6]]) and X.T * X == M([[2, -1, 2], [-1, 5, -1], [2, -1, 2]])
lam = w.eig_desc(XXT)
assert lam == [6, 3]
sg = [w.sig(l) for l in lam]
assert sg == [s6, s3]
u1, u2 = M([0, 1]), M([1, 0])
assert w.is_eigvec(XXT, 6, u1) and w.is_eigvec(XXT, 3, u2)
XTu1, XTu2 = X.T * u1, X.T * u2
assert XTu1 == M([1, -2, 1]) and XTu2 == M([1, 1, 1])
v1 = XTu1 / sg[0]
v2 = XTu2 / sg[1]
assert sp.simplify(v1 - w.unit((1, -2, 1))) == sp.zeros(3, 1) and sp.simplify(v2 - w.unit((1, 1, 1))) == sp.zeros(3, 1)
v3i = M([-1, 0, 1])
assert X * v3i == sp.zeros(2, 1)
Ut, U = w.cols((0, 1), (1, 0))
Vtt, Vt = w.cols_T((1, -2, 1), (1, 1, 1), (-1, 0, 1))
_, V = w.cols((1, -2, 1), (1, 1, 1), (-1, 0, 1))
S = w.S_mat(2, 3, sg)
assert w.check_svd(X, U, S, V)
for i in range(2):                                    # the official solution's separately found pairs also match
    assert sp.simplify(X * V[:, i] - sg[i] * U[:, i]) == sp.zeros(2, 1)
assert X.T * X * v3i == sp.zeros(3, 1)              # v_3 is an eigenvector of A^T A for 0
