"""V02 · AᵀA או AAᵀ: באיזו מהן משתמשים — video script (build: tools/video/vid.py V02).

Source: courses/svd/C02.js (lesson + goal: pick the smaller of A^T A and AA^T, what it gives, how to complete the other
side with v_i = A^T u_i / sigma_i). Exam anchor: 25A-A-Q5a (SVD of the 2x3 [[1,1,1],[1,-2,1]]), solved in full:
AA^T is 2x2 and diagonal, the trap is the order (its first diagonal entry 3 is NOT lambda_1), v_1, v_2 by the formula,
v_3 from ker A, and U S V^T = A — all asserted with sympy below.
Avoided on purpose: the C02 quiz (2x6, [[1,1,0],[0,1,1]], eigenvalues 3,1 of a 3x2, the order steps, [[1,0,2],[2,0,1]]),
the lesson's [[1,0,2],[2,0,1]] (a twin of the boss item 23B-A-Q4a) and 25A-C-Q3a (same matrix as 23B-A-Q4a).
Worked example: the original 2x3 [[2,1,0],[0,1,2]].
Bank note: the official 25A-A solution finds U and V by two separate eigen-decompositions; its signs happen to match
(A v_i = sigma_i u_i holds, asserted below), but the course's method is the formula, which this video uses.
"""
import sympy as sp
